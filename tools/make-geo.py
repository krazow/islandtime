#!/usr/bin/env python3
"""Build src/js/49-geo.js: real shorelines for the in-game maps.
Source: GSHHG full-resolution shorelines (Wessel & Smith, LGPL), github.com/GenericMappingTools/gshhg-gmt,
cut out by tools/gshhg-extract.py into region.json (lon/lat), then clipped to each map's box here."""
import json, math, sys
region = json.load(open(sys.argv[1] if len(sys.argv) > 1 else 'region.json'))
VIEWS = {  # lon0, lon1, lat0, lat1, width
    'I': (-122.752, -122.655, 47.119, 47.196, 400),
    'M': (-122.740, -122.400, 47.080, 47.320, 400),
}
NAMES = {3695: 'ai', 4067: 'mcneil', 4805: 'fox', 20322: 'ketron', 2: 'main'}
def proj(v):
    x0, x1, y0, y1, W = v
    k = math.cos(math.radians((y0 + y1) / 2))
    H = round(W * (y1 - y0) / ((x1 - x0) * k))
    return H, (lambda lon, lat: ((lon - x0) / (x1 - x0) * W, (y1 - lat) / (y1 - y0) * H))
def dp(pts, tol):
    if len(pts) < 3: return pts
    a, b = pts[0], pts[-1]; dmax, idx = 0, 0
    for i in range(1, len(pts) - 1):
        p = pts[i]; dx, dy = b[0] - a[0], b[1] - a[1]; L = math.hypot(dx, dy) or 1e-9
        d = abs(dy * p[0] - dx * p[1] + b[0] * a[1] - b[1] * a[0]) / L
        if d > dmax: dmax, idx = d, i
    if dmax > tol: return dp(pts[:idx + 1], tol)[:-1] + dp(pts[idx:], tol)
    return [a, b]
def clip(pts, x0, x1, y0, y1):
    def ci(p, inside, inter):
        out = []
        for i in range(len(p)):
            a, b = p[i - 1], p[i]
            if inside(b):
                if not inside(a): out.append(inter(a, b))
                out.append(b)
            elif inside(a): out.append(inter(a, b))
        return out
    ix = lambda xv: (lambda a, b: (xv, a[1] + (b[1] - a[1]) * (xv - a[0]) / (b[0] - a[0])))
    iy = lambda yv: (lambda a, b: (a[0] + (b[0] - a[0]) * (yv - a[1]) / (b[1] - a[1]), yv))
    for ins, it in [(lambda q: q[0] >= x0, ix(x0)), (lambda q: q[0] <= x1, ix(x1)), (lambda q: q[1] >= y0, iy(y0)), (lambda q: q[1] <= y1, iy(y1))]:
        pts = ci(pts, ins, it)
        if not pts: break
    return pts
out = {}
for side, v in VIEWS.items():
    H, P = proj(v); W = v[4]; shapes = []
    for poly in region:
        pts = clip(poly['pts'], v[0] - .002, v[1] + .002, v[2] - .002, v[3] + .002)
        if len(pts) < 3: continue
        xy = [P(x, y) for x, y in pts]
        m = len(xy) // 2   # a closed ring: simplify its two halves
        xy = dp(xy[:m + 1], 0.45)[:-1] + dp(xy[m:] + [xy[0]], 0.45)[:-1]
        if len(xy) < 3: continue
        d = 'M' + 'L'.join(f'{x:.1f} {y:.1f}' for x, y in xy) + 'Z'
        shapes.append({'k': 'lake' if poly['level'] == 2 else NAMES.get(poly['id'], 'isle'), 'd': d})
    out[side] = {'bb': list(v[:4]), 'w': W, 'h': H, 'shapes': shapes}
    print(side, W, H, sum(len(s['d']) for s in shapes), 'chars', file=sys.stderr)
js = ('// ---- 🗺️ real shorelines for the maps (generated by tools/make-geo.py; do not edit by hand) ----\n'
      '// Shorelines: GSHHG full resolution, P. Wessel & W.H.F. Smith (LGPL), github.com/GenericMappingTools/gshhg-gmt.\n'
      '// Each side: bb = [lon west, lon east, lat south, lat north], w×h = the SVG viewBox; shapes are land (k: ai, mcneil,\n'
      '// ketron, fox, main, isle) and lakes, already projected into that box.\n'
      'const GEO=' + json.dumps(out, separators=(',', ':')) + ';\n')
open('src/js/49-geo.js', 'w').write(js)
